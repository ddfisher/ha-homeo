"""Feasibility spike: compile reactive bindings to pyscript.

Input (a Python-syntax subset):

    fan.bathroom = sensor.co2 > 800 or sensor.humidity > 50

Output: one pyscript function per binding that re-evaluates the expression
whenever any referenced entity changes, and only writes to the target when
the expression's *result* changes (edge-triggered, so manual overrides stick
until the next transition).
"""

import ast
import sys

# Enough HA domains to tell `sensor.co2` (entity) apart from `x.y` (anything else).
DOMAINS = {
    "binary_sensor", "sensor", "switch", "light", "fan", "cover", "climate",
    "input_boolean", "input_number", "input_select", "lock", "media_player",
    "person", "device_tracker", "sun", "zone", "scene", "script",
}


class CompileError(Exception):
    pass


def entity_id(node):
    """Return 'domain.object' if node is an entity reference, else None."""
    if (isinstance(node, ast.Attribute) and isinstance(node.value, ast.Name)
            and node.value.id in DOMAINS):
        return f"{node.value.id}.{node.attr}"
    return None


class RewriteRefs(ast.NodeTransformer):
    """Replace entity refs with `_val("domain.obj")` and record dependencies."""

    def __init__(self):
        self.deps = []

    def visit_Attribute(self, node):
        eid = entity_id(node)
        if eid is None:
            return self.generic_visit(node)
        if eid not in self.deps:
            self.deps.append(eid)
        return ast.Call(ast.Name("_val", ast.Load()), [ast.Constant(eid)], [])


def compile_source(src):
    tree = ast.parse(src)
    rules, targets = [], set()
    for stmt in tree.body:
        if not (isinstance(stmt, ast.Assign) and len(stmt.targets) == 1):
            raise CompileError(f"line {stmt.lineno}: only `entity = expr` is supported")
        target = entity_id(stmt.targets[0])
        if target is None:
            raise CompileError(f"line {stmt.lineno}: target must be an entity like fan.x")
        if target in targets:
            raise CompileError(f"line {stmt.lineno}: {target} is bound twice")
        targets.add(target)
        rw = RewriteRefs()
        expr = ast.unparse(rw.visit(stmt.value))
        if target in rw.deps:
            raise CompileError(f"line {stmt.lineno}: {target} depends on itself")
        rules.append((stmt.lineno, target, rw.deps, expr))

    out = ["# Generated by ha-dsl spike. Do not edit.",
           "from ha_dsl_runtime import _val, _write, Unknown", "",
           "_last = {}", ""]
    for lineno, target, deps, expr in rules:
        fn = "rule_" + target.replace(".", "_")
        trig = ", ".join(repr(d) for d in deps)
        out += [
            f"# source line {lineno}",
            f"@state_trigger({trig})",
            '@time_trigger("startup")',
            f"def {fn}(**kwargs):",
            "    try:",
            f"        value = bool({expr})",
            "    except Unknown:",
            "        return  # an input is unknown/unavailable: hold current state",
            f"    if _last.get({target!r}) == value:",
            "        return  # inputs changed but result did not: don't fight manual overrides",
            f"    _last[{target!r}] = value",
            f"    _write({target!r}, value)",
            "",
        ]
    return "\n".join(out)


if __name__ == "__main__":
    print(compile_source(open(sys.argv[1]).read()))
